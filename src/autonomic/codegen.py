@dataclass
class Artifact:
    path: str
    content: str
    language: str = "text"
    summary: str = ""
    provider: str = "template"
    risk_notes: list = field(default_factory=list)

    def to_dict(self, include_content: bool = True) -> dict:
        data = {"path": self.path, "language": self.language, "summary": self.summary,
                "provider": self.provider, "risk_notes": self.risk_notes, "bytes": len(self.content)}
        if include_content:
            data["content"] = self.content
        return data


@dataclass
class ValidationReport:
    ok: bool
    checks: list = field(default_factory=list)
    risk: str = "low"
    errors: list = field(default_factory=list)
    requires_approval: bool = False

    def add(self, name: str, ok: bool, detail: str = "") -> None:
        self.checks.append({"check": name, "ok": bool(ok), "detail": detail})
        if not ok:
            self.errors.append(f"{name}: {detail}")

    def to_dict(self) -> dict:
        return {"ok": self.ok, "risk": self.risk, "checks": self.checks,
                "errors": self.errors, "requires_approval": self.requires_approval}


def detect_language(path: str, content: str = "") -> str:
    ext = os.path.splitext(path)[1].lower()
    mapping = {".py": "python", ".sh": "shell", ".bash": "shell", ".yaml": "yaml", ".yml": "yaml",
               ".json": "json", ".service": "systemd", ".conf": "config", ".toml": "toml"}
    if ext in mapping:
        return mapping[ext]
    if path.endswith(".service") or "[Unit]" in content[:200]:
        return "systemd"
    if content.startswith("#!"):
        if "python" in content.splitlines()[0]:
            return "python"
        if "bash" in content.splitlines()[0] or "/sh" in content.splitlines()[0]:
            return "shell"
    return "text"


class CodeGenerator:
    def __init__(self, config: Config, sandbox, backup, policy, audit, logger: Optional[logging.Logger] = None):
        self.config = config
        self.sandbox = sandbox
        self.backup = backup
        self.policy = policy
        self.audit = audit
        self._log = logger or logging.getLogger("autonomic.codegen")
        self.max_bytes = int(config.get("codegen.max_artifact_bytes", 256 * 1024))
        self.sandbox_run = bool(config.get("codegen.sandbox_run", True))
        self.templates_dir = config.get("codegen.templates_dir")

    # -------------------------------------------------------------- generate
    def generate(self, spec: dict) -> dict:
        target = str(spec.get("target_path") or "").strip()
        if not target:
            return {"ok": False, "error": "target_path is required"}
        purpose = str(spec.get("purpose") or "config_fragment")
        language = str(spec.get("language") or detect_language(target))
        provider = "template"

        content, note = self._render_template(purpose, spec, target)
        artifact = Artifact(path=target, content=content, language=language,
                            summary=f"{purpose} generated from deterministic template", provider=provider,
                            risk_notes=[note] if note else [])

        artifact.content = artifact.content.replace("\r\n", "\n")
        self._log.info("generated artifact path=%s provider=%s bytes=%d", artifact.path, artifact.provider,
                       len(artifact.content))
        return {"ok": True, "artifact": artifact, "provider": artifact.provider}

    def _render_template(self, purpose: str, spec: dict, target: str) -> tuple[str, str]:
        name = str(spec.get("name") or os.path.basename(target).split(".")[0] or "service")
        params = {
            "name": name,
            "description": str(spec.get("description") or f"{name} managed by AutonomicOps"),
            "user": str(spec.get("user") or "www-data"),
            "group": str(spec.get("group") or "www-data"),
            "workdir": str(spec.get("workdir") or f"/opt/{name}"),
            "exec_start": str(spec.get("exec_start") or f"/opt/{name}/run.sh"),
            "service_type": str(spec.get("service_type") or "simple"),
            "server_name": str(spec.get("server_name") or "_"),
            "upstream": str(spec.get("upstream") or "http://127.0.0.1:8080"),
            "port": util.parse_int(spec.get("port"), 8080, 1, 65535),
            "host": str(spec.get("host") or "127.0.0.1"),
            "log_glob": str(spec.get("log_glob") or "/var/log/*.log"),
            "rotate": util.parse_int(spec.get("rotate"), 7, 1, 365),
            "maxage": util.parse_int(spec.get("maxage"), 30, 1, 3650),
            "service": str(spec.get("service") or name),
            "content": str(spec.get("content") or "# generated by AutonomicOps"),
        }
        template = TEMPLATES.get(purpose)
        if template is None:
            template = TEMPLATES["config_fragment"]
            note = f"unknown purpose '{purpose}', emitted a config fragment instead"
        else:
            note = ""
        custom = os.path.join(self.templates_dir or "", f"{purpose}.tpl")
        if self.templates_dir and os.path.exists(custom):
            template = util.read_text(custom, template)
        try:
            return template.format(**params), note
        except (KeyError, IndexError, ValueError) as exc:
            self._log.warning("template %s rendering failed: %s", purpose, exc)
            return TEMPLATES["config_fragment"].format(**params), f"template error: {exc}"

    # -------------------------------------------------------------- validate
    def validate(self, artifact: Artifact) -> ValidationReport:
        report = ValidationReport(ok=True)
        content = artifact.content
        self._check_text(report, content)
        self._static_scan(report, content, artifact.path)
        self._syntax_check(report, artifact.path, artifact.language, content)
        if self.sandbox_run:
            self._sandbox_prerun(report, artifact)
        target = os.path.abspath(artifact.path)
        if self.policy.is_forbidden_path(target):
            report.add("target-path", False, f"target is a hard-forbidden path: {target}")
        if self.policy.core.is_core_path(target):
            report.add("core-guard", False, "target is the scheduler core (self-modification disabled) unless "
                                            "policy.core_self_modify is explicitly enabled")
        decision = self.policy.decide(ActionRequest("code.patch", target, {"path": target}))
        report.requires_approval = decision.needs_approval
        report.add("policy", True, decision.reason)
        report.ok = not report.errors
        return report

    def _check_text(self, report: ValidationReport, content: str) -> None:
        report.add("encoding", True, "utf-8 text")
        if len(content.encode("utf-8")) > self.max_bytes:
            report.add("size", False, f"artifact exceeds {self.max_bytes} bytes")
        if "\x00" in content:
            report.add("content", False, "artifact contains NUL bytes")
        if content.strip() == "":
            report.add("content", False, "artifact is empty")
        if len(content.splitlines()) > 4000:
            report.add("size", False, "artifact exceeds 4000 lines; split it into smaller files")

    def _static_scan(self, report: ValidationReport, content: str, path: str) -> None:
        worst = "low"
        hits = []
        for pattern, label, severity in DANGEROUS_PATTERNS:
            if re.search(pattern, content, re.I):
                hits.append({"pattern": label, "severity": severity})
                if {"low": 0, "medium": 1, "high": 2, "critical": 3}[severity] > \
                        {"low": 0, "medium": 1, "high": 2, "critical": 3}[worst]:
                    worst = severity
        report.risk = worst
        if hits:
            detail = "; ".join(f"{h['pattern']}[{h['severity']}]" for h in hits)
            blocked = worst in ("high", "critical")
            report.add("static-risk-scan", not blocked, detail)
        else:
            report.add("static-risk-scan", True, "no dangerous constructs found")
        # path traversal / suspicious target
        if ".." in path or not os.path.isabs(path):
            report.add("target-path", False, f"target must be absolute and contain no '..': {path}")

    def _syntax_check(self, report: ValidationReport, path: str, language: str, content: str) -> None:
        try:
            if language == "python":
                compile(content, path, "exec")
                report.add("python-syntax", True, "compiles")
            elif language == "shell":
                result = self.sandbox.check_shell_syntax(self._temp_file(path, content))
                report.add("shell-syntax", result.ok, (result.stderr or "bash -n passed")[:400])
            elif language == "yaml":
                from .config import parse_yaml
                parse_yaml(content)
                report.add("yaml-syntax", True, "parses")
            elif language == "json":
                json.loads(content)
                report.add("json-syntax", True, "parses")
            elif language == "systemd":
                parser = configparser.ConfigParser(strict=False, allow_no_value=True)
                parser.read_string(content)
                has_service = parser.has_section("Service")
                report.add("systemd-syntax", has_service, "has [Service] section" if has_service else "missing [Service]")
            elif language == "nginx":
                depth = 0
                for ch in content:
                    depth += 1 if ch == "{" else -1 if ch == "}" else 0
                    if depth < 0:
                        break
                report.add("nginx-braces", depth == 0, "balanced braces" if depth == 0 else "unbalanced braces")
            else:
                report.add("format", True, "no dedicated syntax checker; static scan only")
        except Exception as exc:  # noqa: BLE001
            report.add(f"{language}-syntax", False, util.redact(str(exc))[:300])

    def _temp_file(self, path: str, content: str) -> str:
        tag = util.new_id("cg_")
        tmp = os.path.join(self.sandbox.root, f"validate-{tag}-{os.path.basename(path)}")
        util.atomic_write(tmp, content, mode=0o700)
        return tmp

    def _sandbox_prerun(self, report: ValidationReport, artifact: Artifact) -> None:
        if artifact.language not in ("python", "shell"):
            report.add("sandbox-prerun", True, "not an executable artefact; pre-run skipped")
            return
        tmp = self._temp_file(artifact.path, artifact.content)
        try:
            args = ["--selftest"] if artifact.language == "python" and "--selftest" in artifact.content else []
            if artifact.language == "shell" and "AUTONOMIC_DRY_RUN" not in artifact.content:
                report.add("sandbox-prerun", False,
                           "shell artefact does not honour AUTONOMIC_DRY_RUN; refusing to execute it during validation")
                return
            result = self.sandbox.run_script(tmp, args=args, timeout=float(self.config.get("codegen.sandbox_timeout", 10)))
            notes = "; ".join(result.notes)[:300]
            report.add("sandbox-prerun", result.ok,
                       f"rc={result.rc} {notes} stderr={result.stderr[:200]}")
        finally:
            try:
                os.unlink(tmp)
            except OSError:
                pass

    # ----------------------------------------------------------------- apply
    def apply(self, artifact: Artifact, approved: bool = False, actor: str = "cli") -> dict:
        validation = self.validate(artifact)
        if not validation.ok:
            return {"ok": False, "status": "rejected", "detail": "; ".join(validation.errors),
                    "validation": validation.to_dict()}
        if validation.requires_approval and not approved:
            self._publish_patch_request(artifact)
            return {"ok": False, "status": "pending_approval",
                    "detail": "artifact requires human approval; proposal stored",
                    "validation": validation.to_dict()}

        target = os.path.abspath(artifact.path)
        try:
            self.policy.core.guard_write(target, approved=approved)
        except Exception as exc:  # noqa: BLE001 - PolicyDenied
            return {"ok": False, "status": "denied", "detail": str(exc)}

        existed = os.path.exists(target)
        snapshot = self.backup.snapshot([target], label="code-apply",
                                       meta={"actor": actor, "provider": artifact.provider})
        mode = 0o600 if any(word in target.lower() for word in ("secret", "token", "key", "credential")) else 0o644
        util.atomic_write(target, artifact.content, mode=mode)
        actual = util.sha256_file(target)
        expected = util.sha256_text(artifact.content)
        verified = actual == expected
        detail = f"{'updated' if existed else 'created'} {target} ({len(artifact.content)} bytes, sha256={actual[:16]})"
        self.audit.record(
            actor=actor, trigger="codegen.apply", action="code.patch", target=target,
            params={"provider": artifact.provider, "bytes": len(artifact.content)},
            result=("OK: " if verified else "FAILED: ") + detail,
            files_changed=[target], rollback_point=snapshot["id"],
            extra={"validation": validation.to_dict(), "snapshot_complete": snapshot.get("complete")},
        )
        self._log.info("code applied target=%s verified=%s snapshot=%s", target, verified, snapshot["id"])
        return {"ok": verified, "status": "applied", "detail": detail, "changed_files": [target],
                "rollback_point": snapshot["id"], "verified": verified,
                "snapshot_complete": snapshot.get("complete"), "validation": validation.to_dict()}

    def _publish_patch_request(self, artifact: Artifact) -> None:
        request = ActionRequest(
            action="code.patch", target=artifact.path,
            params={"spec": {"target_path": artifact.path, "content": artifact.content,
                             "purpose": "patch", "language": artifact.language},
                    "provider": artifact.provider},
            source="user", reason="codegen artifact requires approval",
        )
        # The daemon wires this method to the coordinator; if unwired we still
        # persist a proposal through the audit log so nothing is lost.
        if getattr(self, "publish", None):
            self.publish("action.request", {"request": request.to_dict()})
        else:
            self.audit.record(actor="codegen", trigger="codegen.apply", action="code.patch", target=artifact.path,
                              params={"bytes": len(artifact.content)}, result="proposal (no coordinator wired)")

    def generate_and_apply(self, spec: dict, approved: bool = False, actor: str = "cli") -> dict:
        if not self.config.get("codegen.enabled", True):
            return {"ok": False, "status": "disabled", "detail": "codegen.enabled=false"}
        generated = self.generate(spec)
        if not generated.get("ok"):
            return generated
        artifact: Artifact = generated["artifact"]
        result = self.apply(artifact, approved=approved, actor=actor)
        result["artifact"] = artifact.to_dict(include_content=True)
        result["generation"] = {"provider": artifact.provider}
        return result

    # ------------------------------------------------------------------ misc
    def preview(self, spec: dict) -> dict:
        generated = self.generate(spec)
        if not generated.get("ok"):
            return generated
        artifact: Artifact = generated["artifact"]
        validation = self.validate(artifact)
        return {"ok": validation.ok, "artifact": artifact.to_dict(), "validation": validation.to_dict(),
                "provider": artifact.provider}

    def stats(self) -> dict:
        return {"enabled": bool(self.config.get("codegen.enabled", True)),
                "max_bytes": self.max_bytes, "sandbox_run": self.sandbox_run,
                "templates": sorted(TEMPLATES)}
