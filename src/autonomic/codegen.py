"""Code generation, validation, sandbox pre-run and guarded apply.

Pipeline (nothing is ever written straight to disk):

    spec -> generate (deterministic template)
         -> static risk scan (forbidden constructs, secret leakage patterns)
         -> syntax check (python compile / bash -n / yaml / json / unit file)
         -> sandbox pre-run (generated artefacts only; disposable dir, rlimits)
         -> policy gate (core files, forbidden paths, approval class)
         -> snapshot -> atomic write -> hash verify -> audit

If any stage fails the artefact is rejected with a machine-readable reason.
Generated output is treated as untrusted text exactly like a plugin author's.
"""

