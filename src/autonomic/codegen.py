DANGEROUS_PATTERNS = [
    (r"rm\s+-rf\s+/\s*($|;|&)", "recursive delete of root", "critical"),
    (r"rm\s+-rf\s+/\*", "recursive delete of /*", "critical"),
    (r"mkfs(\.|\s)", "filesystem format", "critical"),
    (r"dd\s+if=.*of=/dev/", "raw disk write", "critical"),
    (r">\s*/dev/(sd|nvme|hd)", "raw device overwrite", "critical"),
    (r":\(\)\s*\{\s*:\|:&\s*\};:", "fork bomb", "critical"),
    (r"\bsudoers\b", "sudoers modification", "critical"),
    (r"chmod\s+777\s+/", "world-writable root path", "high"),
    (r"chmod\s+[ugoa]*\+s\s+/", "setuid on system path", "high"),
    (r"iptables\s+-F", "flush all firewall rules (self-lockout risk)", "high"),
    (r"\bshutdown\b|\breboot\b|\bpoweroff\b", "host power control", "high"),
    (r"curl\s+[^\n|]*\|\s*(?:ba)?sh", "remote code execution via pipe", "critical"),
    (r"wget\s+[^\n|]*\|\s*(?:ba)?sh", "remote code execution via pipe", "critical"),
    (r"base64\s+(?:-d|--decode)[^\n|]*\|\s*(?:ba)?sh", "obfuscated execution", "critical"),
    (r"eval\s*\(\s*(?:input|sys\.stdin|requests)", "eval of untrusted input", "high"),
    (r"os\.system\s*\(", "shell invocation via os.system", "medium"),
    (r"subprocess\.\w+\([^)]*shell\s*=\s*True", "shell=True subprocess", "medium"),
    (r"/etc/(?:passwd|shadow|sudoers)", "credential file access", "high"),
    (r"(?i)(api[_-]?key|secret|token)\s*=\s*['\"][A-Za-z0-9_\-]{16,}", "hard-coded credential", "high"),
]

